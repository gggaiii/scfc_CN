function sourceLabel(url) {
  const {hostname,pathname}=new URL(url);
  if(hostname==='www.premierleague.com')return '英超官方升级报道';
  if(hostname==='rochdaleafc.co.uk')return '罗奇代尔官方离队公告';
  if(hostname==='careers.stockportcounty.com')return '俱乐部官方教练团队';
  if(hostname==='www.mansfieldtown.net')return '曼斯菲尔德官方比赛名单';
  if(pathname.startsWith('/news/')){
    const [,year,month,day]=pathname.split('/').filter(Boolean);
    const months={january:1,february:2,march:3,april:4,may:5,june:6,july:7,august:8,september:9,october:10,november:11,december:12};
    return `${year}年${months[month]}月${Number(day)}日 · 官方公告`;
  }
  return '俱乐部官方人物介绍';
}
function profile(shortIntro, highlights, sections, source) {
  const urls = Array.isArray(source) ? source : [source.startsWith('https:') ? source : `${club}/teams/men/${source}`];
  return {shortIntro, highlights, detailSections: sections.map(section), profileSources: urls.map(url => ({url, label: sourceLabel(url)})), profileUpdatedAt: '2026-11-14'};
}

